import assert from 'node:assert/strict'
import { chromium } from 'playwright'
import AxeBuilder from '@axe-core/playwright'
import { serveAuthProduction } from './lib/auth-production.mjs'
import { updateReport } from './lib/report.mjs'

const host = await serveAuthProduction()
const browser = await chromium.launch({ channel: process.env.MONEE_BROWSER ?? 'msedge', headless: true })
const report = { ok: false, provider: 'Signed synthetic Access identity; no real email delivery or production data', runtime: 'workerd + D1', scenarios: [], layouts: [], errors: [] }
try {
  const desktop = await browser.newContext({ viewport: { width: 1366, height: 900 }, reducedMotion: 'reduce', serviceWorkers: 'block' })
  const page = await desktop.newPage()
  page.on('pageerror', error => report.errors.push(error.message))
  await page.goto(host.origin)
  await page.getByRole('heading', { name: 'Masuk ke Monee' }).waitFor()
  await page.getByRole('button', { name: 'Buat akun', exact: true }).click()
  await page.getByRole('button', { name: 'Verifikasi email', exact: true }).click()
  await page.getByRole('heading', { name: 'Buat PIN akunmu' }).waitFor()
  await page.getByLabel('PIN akun 6 digit', { exact: true }).fill('582916')
  await page.getByLabel('Konfirmasi PIN akun', { exact: true }).fill('582916')
  await page.getByRole('button', { name: 'Simpan PIN dan lanjutkan' }).click()
  await page.getByLabel('Nama panggilan').waitFor()
  report.scenarios.push('Register through signed Access proof and create account PIN')
  await page.getByLabel('Nama panggilan').fill('Akun Uji')
  await page.getByRole('button', { name: /Lanjut/ }).click()
  await page.getByRole('button', { name: 'Lewati dulu', exact: true }).click()
  await page.getByRole('button', { name: /Lanjut/ }).click()
  await page.getByRole('button', { name: /Pilih.*ini/ }).click()
  await page.getByRole('navigation', { name: 'Navigasi utama' }).waitFor()
  report.scenarios.push('Four-step onboarding without a second PIN prompt')
  await page.getByRole('link', { name: 'Atur', exact: true }).click()
  await page.getByRole('button', { name: /Ganti PIN akun/ }).waitFor()
  await page.reload()
  await page.getByRole('heading', { name: 'Atur', exact: true }).waitFor()
  report.scenarios.push('Trusted desktop reopens directly without email verification or PIN')
  const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, reducedMotion: 'reduce', serviceWorkers: 'block' })
  const phone = await mobile.newPage()
  await phone.goto(host.origin)
  await phone.getByLabel('Email', { exact: true }).fill('one@qa.invalid')
  await phone.getByLabel('PIN akun 6 digit', { exact: true }).fill('582916')
  await phone.getByRole('button', { name: 'Masuk', exact: true }).click()
  await phone.getByRole('navigation', { name: 'Navigasi utama' }).waitFor()
  await phone.getByRole('link', { name: 'Atur', exact: true }).click()
  await phone.getByRole('button', { name: /Ubah nama, sekarang Akun Uji/ }).waitFor()
  report.scenarios.push('Fresh phone logs in using email/PIN and pulls existing profile without onboarding')
  await phone.getByRole('button', { name: /Ganti PIN akun/ }).click()
  await phone.getByLabel('PIN akun saat ini', { exact: true }).fill('582916')
  await phone.getByLabel('PIN akun baru', { exact: true }).fill('739152')
  await phone.getByLabel('Konfirmasi PIN baru', { exact: true }).fill('739152')
  await phone.getByRole('button', { name: 'Simpan PIN akun', exact: true }).click()
  await phone.getByRole('dialog').waitFor({ state: 'hidden' })
  await page.reload()
  await page.getByRole('heading', { name: 'Masuk ke Monee' }).waitFor()
  report.scenarios.push('Changing PIN revokes the other device session')
  for (const width of [320, 390, 768, 1366]) {
    await page.setViewportSize({ width, height: 900 })
    const metrics = await page.evaluate(() => ({ width: innerWidth, scrollWidth: document.documentElement.scrollWidth }))
    assert.ok(metrics.scrollWidth <= width, `Login overflow at ${width}`)
    report.layouts.push(metrics)
  }
  const axe = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
  assert.equal(axe.violations.length, 0, JSON.stringify(axe.violations.map(item => ({ id: item.id, impact: item.impact }))))
  report.scenarios.push('Login layouts 320/390/768/1366 and WCAG AA automated checks')
  await page.getByRole('button', { name: 'Lupa PIN', exact: true }).click()
  await page.getByRole('button', { name: 'Verifikasi email', exact: true }).click()
  await page.getByRole('heading', { name: 'Buat PIN akunmu' }).waitFor()
  await page.getByLabel('PIN akun 6 digit', { exact: true }).fill('916285')
  await page.getByLabel('Konfirmasi PIN akun', { exact: true }).fill('916285')
  await page.getByRole('button', { name: 'Simpan PIN dan lanjutkan' }).click()
  await page.getByRole('navigation', { name: 'Navigasi utama' }).waitFor()
  await phone.reload()
  await phone.getByRole('heading', { name: 'Masuk ke Monee' }).waitFor()
  report.scenarios.push('Recover PIN using a new signed verification and revoke all prior sessions')
  await page.getByRole('link', { name: 'Atur', exact: true }).click()
  await page.getByRole('button', { name: 'Keluar dari akun', exact: true }).click()
  await page.getByRole('heading', { name: 'Masuk ke Monee' }).waitFor()
  await page.getByLabel('Email', { exact: true }).fill('one@qa.invalid')
  await page.getByLabel('PIN akun 6 digit', { exact: true }).fill('916285')
  await page.getByRole('button', { name: 'Masuk', exact: true }).click()
  await page.getByRole('navigation', { name: 'Navigasi utama' }).waitFor()
  report.scenarios.push('Explicit logout followed by normal PIN login')
  assert.deepEqual(report.errors, [])
  report.ok = true
} finally {
  await browser.close(); await host.close(); await updateReport('account-pin-e2e', report)
  console.log(JSON.stringify(report, null, 2))
}
